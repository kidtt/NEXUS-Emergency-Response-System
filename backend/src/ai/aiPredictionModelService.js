const pool = require("../config/database");

const saveAIPrediction = async (
    incidentId,
    analysis
) => {
    const [result] = await pool.execute(
        `INSERT INTO ai_predictions (
            incident_id,
            predicted_type,
            predicted_severity,
            severity_score,
            priority_score,
            risk_level,
            confidence_score,
            recommended_team,
            recommendation,
            explanation,
            response_action
        )
        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
        [
            incidentId,
            analysis.classification,
            analysis.predicted_severity,
            analysis.severity_score,
            analysis.priority_score,
            analysis.risk_level,
            analysis.confidence_score,
            analysis.recommended_team,
            analysis.recommendation,
analysis.explanation,
analysis.response_action        ]
    );

    return result.insertId;
};


const getIncidentPredictions = async (
    incidentId
) => {
    const [predictions] = await pool.execute(
        `SELECT *
         FROM ai_predictions
         WHERE incident_id = ?
         ORDER BY created_at DESC`,
        [incidentId]
    );

    return predictions;
};

const saveMLPrediction = async (
    incidentId,
    prediction
) => {

    const [result] = await pool.execute(
        `INSERT INTO ai_predictions (
            incident_id,
            predicted_type,
            predicted_severity,
            confidence_score,
            model_version,
            explanation,
            response_action
        )
        VALUES (?, ?, ?, ?, ?, ?, ?)`,
        [
            incidentId,
            null,
            prediction.prediction,
            prediction.confidence,
            "random-forest-v1",
            "Prediction generated by the NEXUS machine learning model.",
            "ML prediction generated. Review alongside rule-based emergency intelligence."
        ]
    );

    return result.insertId;
};
module.exports = {
    saveAIPrediction,
    getIncidentPredictions,
    saveMLPrediction
};